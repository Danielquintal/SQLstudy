CREATE TABLE IF NOT EXISTS "Pacientes" (
	"id_pacientes" INTEGER NOT NULL,
	"id_clinica" VARCHAR(255),
	"nome" VARCHAR(255),
	"telefone" VARCHAR(255),
	"email" VARCHAR(255),
	"endereço" VARCHAR(255),
	PRIMARY KEY("id_pacientes")
);

CREATE TABLE IF NOT EXISTS "Fornecedores" (
	"id_fornecedores" INTEGER NOT NULL,
	"nome" VARCHAR(255),
	"telefone" VARCHAR(255),
	PRIMARY KEY("id_fornecedores")
);

CREATE TABLE IF NOT EXISTS "Clínica" (
	"id_clinica" INTEGER NOT NULL,
	"nome" VARCHAR(255),
	"endereço" VARCHAR(255),
	"telefone" VARCHAR(255),
	PRIMARY KEY("id_clinica")
);

CREATE TABLE IF NOT EXISTS "Profissionais" (
	"id_profissional" INTEGER NOT NULL UNIQUE,
	"nome" VARCHAR(255),
	"especialidade" VARCHAR(255),
	"email" VARCHAR(255),
	"telefone" VARCHAR(255),
	PRIMARY KEY("id_profissional")
);

CREATE TABLE IF NOT EXISTS "Consultas" (
	"id_consultas" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"id_clinica" VARCHAR(255),
	"data" DATE,
	"id_profissional" VARCHAR(255),
	"id_pacientes" VARCHAR(255),
	PRIMARY KEY("id_consultas")
);

